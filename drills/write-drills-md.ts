// drills/write-drills-md.ts
// Regenerates DRILLS.md from real runs: every drill is run in a scratch copy
// and its actual output is pasted in, so the book can quote DRILLS.md safely.
//   node drills/write-drills-md.ts      (takes a few minutes)
// Exits 1, and writes nothing, if any drill misbehaves.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { listFiles } from '../guards/lib/files.ts';
import { loadDrills, runDrill, type Drill, type PhaseResult } from './run.ts';

const fence = (text: string, lang = 'text') => `\`\`\`${lang}\n${text.trimEnd()}\n\`\`\``;

// Temp folders differ on every run and machine, so show a stable name.
// Playwright's colour codes and box-drawing rules mean nothing on paper, so drop them.
const tidy = (text: string) =>
  text
    .replaceAll(tmpdir(), '$TMPDIR')
    .replace(/\x1b\[[0-9;]*m/g, '')
    .replace(/ ?\u2500+/g, '');

// The changed lines of a patch (or only those mentioning a highlight word).
function excerpt(patch: string, highlight: string[] = [], max = 14): string {
  const changed = patch
    .split('\n')
    .filter((l) => /^[+-]/.test(l) && !/^(\+\+\+|---) /.test(l))
    .filter((l) => highlight.length === 0 || highlight.some((word) => l.includes(word)));
  const more = changed.length > max ? `\n... (${changed.length - max} more changed lines)` : '';
  return changed.slice(0, max).join('\n') + more;
}

// The opening sentences of a file's header comment, skipping the "// guards/x.ts" path line.
function summary(file: string): string {
  const comment: string[] = [];
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (!line.startsWith('//')) break;
    comment.push(line.slice(3));
  }
  if (/^[\w/.-]+\.ts$/.test(comment[0] ?? '')) comment.shift();
  // Whole sentences, until there are at least 40 characters: "One gate that refuses." alone says too little.
  const sentences = comment.join(' ').split(/(?<=[.?])\s+/); // "AGENTS.md" is not a sentence end
  const kept: string[] = [];
  for (const sentence of sentences) {
    if (kept.join(' ').length >= 40) break;
    kept.push(sentence);
  }
  return kept.join(' ');
}

function section(folder: string, drill: Drill, before: PhaseResult, after: PhaseResult, stat: string): string {
  const parts = [
    `## ${drill.id} ${drill.title}`,
    `Chapter ${drill.chapter}, card ${drill.card}. Folder: \`drills/${folder}/\`. Run it: \`npm run drill ${drill.id}\``,
    `**The mistake.** ${drill.mistake}`,
    `**Files.** ${drill.files.map((f) => `\`${f}\``).join(', ')}`,
  ];
  if (drill.patch) {
    const patch = readFileSync(`drills/${folder}/${drill.patch}`, 'utf8');
    parts.push(`**Mistake patch** (\`drills/${folder}/${drill.patch}\`):`, fence(stat));
    parts.push(drill.highlight ? `Key lines (those mentioning ${drill.highlight.join(', ')}):` : 'Key lines:', fence(excerpt(patch, drill.highlight), 'diff'));
  } else {
    parts.push('**Script drill** (no patch): the before and after runs are different commands.');
  }
  if (drill.setup) parts.push(`**Setup**, run once first: \`${drill.setup}\``);
  parts.push(`**Before**: \`${before.command}\` (exit ${before.exit})`, fence(tidy(before.output)));
  parts.push(`**After**: \`${after.command}\` (exit ${after.exit})`, fence(tidy(after.output)));
  return parts.join('\n\n');
}

const drills = loadDrills();
const sections: string[] = [];
const rows: string[] = [];
for (const { folder, drill } of drills) {
  process.stdout.write(`running ${drill.id} ... `);
  const result = runDrill(folder, drill, false);
  console.log(result.ok ? 'ok' : 'NOT AS EXPECTED');
  if (!result.ok) process.exit(1);
  rows.push(`| ${drill.id} | ${drill.title} | ${drill.chapter} | ${drill.card} | \`npm run drill ${drill.id}\` | exit ${result.before.exit} | exit ${result.after.exit} |`);
  sections.push(section(folder, drill, result.before, result.after, result.stat));
}

const codeFiles = [...listFiles('guards', ['.ts']).filter((f) => !f.includes('/test/')), ...listFiles('toy-agent', ['.ts']).filter((f) => !f.includes('/test/') && !f.includes('/workspace/'))];
const guardRows = codeFiles.map((f) => `| \`${f}\` | ${readFileSync(f, 'utf8').trimEnd().split('\n').length} | ${summary(f)} |`);

const doc = `# Drills

Generated by \`npm run drills:docs\` from real runs on Node ${process.versions.node}. Do not edit by hand: change the
code or the drill, then regenerate. Timings, ports and temporary paths (shown as \`$TMPDIR\`) vary between runs.
Terminal colour codes and Playwright's horizontal rules are removed; everything else is exactly what the commands print.

Each drill copies the repository to a scratch folder, runs the "before" command, makes one agent mistake (applies
the drill's patch, or runs a different script), runs the "after" command, and checks both exit codes and outputs
against \`drill.json\`. Your working tree is never changed. \`npm run drills\` runs all ${drills.length} and exits 0 only if
every one behaves as expected.

| ID | Title | Chapter | Card | Command | Before | After |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Guard and agent files

Line counts include comments. The summary is the start of each file's header comment.

| File | Lines | Summary |
|---|---|---|
${guardRows.join('\n')}

${sections.join('\n\n')}

## Making your own drill

1. Make the mistake by hand in a scratch copy of the repository (a git checkout), then save it:
   \`git diff > drills/DNN-slug/mistake.patch\` (add new files with \`git add -N\` first so they appear in the diff).
2. Write \`drills/DNN-slug/drill.json\` with the guard command and the exit code and text you expect before and after.
3. Run \`npm run drill DNN\` until it behaves, then regenerate this file.
`;

writeFileSync('DRILLS.md', doc);
console.log(`wrote DRILLS.md (${drills.length} drills, ${codeFiles.length} files listed)`);
// Folders that are not drills are ignored by loadDrills(); list them so nothing is forgotten.
const strays = readdirSync('drills').filter((d) => !/^D\d\d-/.test(d) && !d.endsWith('.ts'));
if (strays.length > 0) console.log(`note: not drills: ${strays.join(', ')}`);
